namespace LynnaLab;

public class HelpWindow : Frame
{
    // ================================================================================
    // Constructors
    // ================================================================================
    public HelpWindow() : base("Help")
    {
        base.DefaultSize = new Vector2(600.0f, 800.0f);
    }

    // ================================================================================
    // Variables
    // ================================================================================

    HelpWidget helpWidget = new();

    // ================================================================================
    // Properties
    // ================================================================================

    public HelpWidget HelpWidget { get { return helpWidget; } }

    // ================================================================================
    // Public methods
    // ================================================================================

    public override void Render()
    {
        helpWidget.Render();
    }

    public void SetProject(Project p)
    {
        HelpWidget.SetProject(p);
    }

    // ================================================================================
    // Private methods
    // ================================================================================
}
